/**
 * Константы формулы рейтинга KTTF, версия 3.0 — формула RTTF, ADR-069.
 *
 * Значения взяты с первоисточника (rttf.ru/content/2, редакция 01.05.2026)
 * без изменений: игроки, перешедшие с RTTF, обязаны получить те же числа,
 * что получили бы там. Собраны здесь целиком: правка формулы — правка одного
 * файла плюс пересчёт истории из журнала RatingEvent.
 */

/**
 * Разрыв рейтингов, при котором победа фаворита перестаёт давать очки.
 * Он же числитель формулы: Δ = (GAP_ZERO − (Rв − Rп)) / DELTA_DIVISOR × k × D.
 */
export const GAP_ZERO = 100;

/** Делитель формулы: при равных рейтингах базовая дельта равна 10. */
export const DELTA_DIVISOR = 10;

/** Рейтинг не опускается ниже этого значения. */
export const MIN_RATING = 1;

/** Стартовый рейтинг нового игрока, если организатор не оценил его сам (ADR-062). */
export const START_RATING = 250;

/**
 * Новичок — игрок в первых пяти своих рейтинговых турнирах.
 * Сыграв столько турниров, он считается по общим правилам.
 */
export const NOVICE_TOURNAMENTS = 5;

/** k новичка при победе: растёт к своей силе быстро. */
export const NOVICE_K_WIN = 1;

/** k новичка при поражении: падает вдвое медленнее, чем растёт. */
export const NOVICE_K_LOSS = 0.5;

/** D новичка: счёт встречи для него не важен. */
export const NOVICE_SCORE_MULTIPLIER = 1;

/**
 * Коэффициент турнира k по среднему рейтингу участников на старте.
 *
 * В первоисточнике все неравенства строгие и границы не определены.
 * Граница относится к верхнему диапазону: средний 250 даёт 0.25.
 */
export const TOURNAMENT_FACTOR: readonly { readonly below: number; readonly k: number }[] = [
  { below: 250, k: 0.2 },
  { below: 350, k: 0.25 },
  { below: 450, k: 0.3 },
  { below: 550, k: 0.35 },
];

/** k турнира, средний рейтинг которого не ниже последней границы. */
export const TOURNAMENT_FACTOR_TOP = 0.4;

/** Коэффициент счёта D по разнице в сетах. */
export const SCORE_MULTIPLIER = {
  ONE_SET: 0.8,
  TWO_SETS: 1.0,
  THREE_PLUS: 1.2,
} as const;

/** Бонус призёрам начисляется, только если участников не меньше. */
export const BONUS_MIN_PARTICIPANTS = 16;

/** Сила турнира для бонуса — средний рейтинг стольких сильнейших. */
export const BONUS_TOP_PLAYERS = 12;

/**
 * Бонус в процентах от рейтинга призёра на старте по его превосходству
 * над средним рейтингом сильнейших. Призёр, превосходящий их больше чем
 * на последнюю границу, бонуса не получает: он выиграл турнир не своего уровня.
 */
export const BONUS_PERCENT: readonly {
  readonly upTo: number;
  readonly places: readonly [number, number, number];
}[] = [
  { upTo: 100, places: [2.5, 1.5, 1] },
  { upTo: 150, places: [2, 1, 0.5] },
  { upTo: 200, places: [1, 0.5, 0] },
];
