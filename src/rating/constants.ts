import type { TournamentLevel } from './types.js';

/**
 * Константы формулы рейтинга KTTF, версия 2.0.
 *
 * Значения стартовые и подлежат калибровке на реальных турнирных протоколах
 * до пилота (02-requirements.md, раздел 7.5, открытый вопрос ОВ-3). Они собраны
 * здесь целиком: калибровка — правка одного файла плюс пересчёт истории
 * из журнала RatingEvent.
 */

/** Шкала логистической функции Эло. */
export const SCALE = 200;

/**
 * Разрыв рейтингов, при котором победа фаворита перестаёт давать очки.
 * Правило конкурента, к которому привыкли игроки: победа над заведомо
 * более слабым не является информацией о силе игрока.
 */
export const GAP_ZERO = 100;

/** Рейтинг не опускается ниже этого значения. */
export const MIN_RATING = 1;

/** Стартовый рейтинг нового игрока. */
export const START_RATING = 250;

/** Сыграв столько рейтинговых встреч, игрок перестаёт быть провизорным. */
export const PROVISIONAL_THRESHOLD = 20;

/** K рейтингового игрока. Единый: градация по уровню рейтинга удалена в ADR-003. */
export const K_BASE = 20;

/** K провизорного игрока при победе. Вдвое выше базового — новичок должен быстро дойти до своей силы. */
export const K_PROV_WIN = 40;

/**
 * K провизорного игрока при поражении.
 *
 * Совпадает с K_BASE намеренно: новичок растёт быстрее, чем падает, но падает
 * с обычной скоростью. Следствие, важное для понимания inbalance: расхождение
 * дельт возникает только когда провизорен ПОБЕДИТЕЛЬ.
 */
export const K_PROV_LOSS = 20;

/** Коэффициент турнира T. */
export const LEVEL_FACTOR: Readonly<Record<TournamentLevel, number>> = {
  CLUB: 0.8,
  REGIONAL: 1.0,
  NATIONAL: 1.2,
};

/** Множитель за счёт M. */
export const SCORE_MULTIPLIER = {
  ONE_SET: 0.8,
  TWO_SETS: 1.0,
  THREE_PLUS: 1.2,
} as const;
