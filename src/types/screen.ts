import { z } from 'zod';

import { playerViewSchema } from './player.js';
import { stageViewSchema } from './stage.js';
import { tournamentStandingsSchema } from './standings.js';
import { tournamentViewSchema } from './tournament.js';

/**
 * Второй экран зала — ТЗ 6.5, маршрут ТС 7.7.
 *
 * Это монитор на стене, а не страница для человека с телефоном: он ничего не
 * отправляет и никого не спрашивает. Отсюда состав ответа — ровно то, что на
 * нём показывается: столы с текущими встречами, очередь ближайших и групповые
 * таблицы. Журнала рейтинга здесь нет: он ничего не добавляет зрителю в зале,
 * а по публичному токену открывается кому угодно.
 *
 * Столы и очередь **не приходят готовыми**: их выводит клиент теми же чистыми
 * функциями, что и консоль судьи. Второе правило очереди на сервере означало
 * бы, что стена и консоль расходятся в порядке вызова пар.
 */

export const screenViewSchema = z.object({
  tournament: tournamentViewSchema,
  /**
   * Состав турнира: экран разворачивает по нему идентификаторы в фамилии.
   *
   * Отдельным списком, а не полем внутри встречи: один игрок попадает и в
   * таблицу, и в очередь, и на стол, а дублировать его карточку трижды в
   * ответе, который обновляется после каждой встречи, — лишний трафик на
   * канале, который в зале и так узкий.
   */
  players: z.array(playerViewSchema),
  standings: tournamentStandingsSchema,
  stages: z.array(stageViewSchema),
  /**
   * Момент сборки ответа.
   *
   * Нужен экрану, а не серверу: при обрыве связи стена продолжает показывать
   * последнее состояние, и зритель обязан видеть, насколько оно свежее.
   */
  updatedAt: z.iso.datetime(),
});
export type ScreenView = z.infer<typeof screenViewSchema>;

/**
 * Имена событий потока — ТС 7.7.
 *
 * `state` несёт `ScreenView` целиком: экран не склеивает изменения, он
 * заменяет состояние. Диффы потребовали бы порядка доставки и восстановления
 * пропущенного — то есть протокола, которого у монитора на стене быть не
 * должно.
 *
 * `ping` не несёт ничего и существует ради посредников: прокси рвут
 * соединение, в котором долго молчат, а между встречами в зале пауза
 * измеряется минутами.
 */
export const SCREEN_EVENTS = { state: 'state', ping: 'ping' } as const;

export const screenPingSchema = z.object({ at: z.iso.datetime() });
export type ScreenPing = z.infer<typeof screenPingSchema>;
